/**
 * Regression checks for the shared native path's page furniture, exercised on
 * real generated PDF bytes (no preview, no approval artifact).
 */
import { describe, expect, it } from 'vitest'
import { getDocument, OPS } from 'pdfjs-dist/legacy/build/pdf.mjs'
import { projeterRequeteExport } from '@/fiche/prototype/cahierExportCapture'
import { capturePdfFixture } from './helpers/cahierPdfFixtures'
import { cahierExportFixture, sectionOf } from './helpers/cahierExportFixtures'
import { composerCahierPdfNativedansNavigateur } from './helpers/cahierPdfNativeRuntime'

async function generate(capture: ReturnType<typeof capturePdfFixture>) {
  const offered = capture.capabilities.selectableSeries.map((serie) => serie.id)
  const projection = projeterRequeteExport(capture, offered.slice(0, 3))
  if (projection.status !== 'ready') throw new Error(projection.reason)
  const result = await composerCahierPdfNativedansNavigateur(projection.request, {
    signal: new AbortController().signal,
  })
  const bytes = new Uint8Array(await result.blob.arrayBuffer())
  const pdf = await getDocument({ data: Uint8Array.from(bytes) }).promise
  const page = await pdf.getPage(1)
  return { bytes, pdf, page, items: (await page.getTextContent()).items.filter((item) => 'str' in item && item.str) as any[] }
}

describe('Cahier PDF natif — mobilier de page', () => {
  it('places each rotated y-axis title beside its own ticks, inside its figure', async () => {
    const { items } = await generate(capturePdfFixture('aedar-access'))
    const rotated = items.filter((item) => {
      const angle = Math.atan2(item.transform[1], item.transform[0]) * 180 / Math.PI
      return Math.abs(Math.abs(angle) - 90) < 2 && /DIVERSITÉ|VOLUME DE L’OFFRE/.test(item.str)
    })
    expect(rotated.length).toBe(2)
    // The mounted SVG's own y tick labels are the reference: each title must
    // sit a small native gap to the LEFT of its figure's ticks and on the same
    // vertical span (not merely "somewhere left of the x-axis").
    const yTicks = items.filter((item) => ['0', '3', '5', '9', '10'].includes(item.str)
      && Math.abs(item.transform[1]) < 0.01
      && item.transform[5] > 520 && item.transform[5] < 610)
    expect(yTicks.length).toBeGreaterThanOrEqual(2)
    for (const title of rotated) {
      const titleX = title.transform[4] as number
      const own = yTicks.filter((tick) => {
        const gap = (tick.transform[4] as number) - titleX
        return gap > 0 && gap < 30 && Math.abs(tick.transform[5] - title.transform[5]) < 70
      })
      expect(own.length, `y ticks beside ${title.str}`).toBeGreaterThanOrEqual(1)
      expect(Math.min(...own.map((tick) => (tick.transform[4] as number) - titleX))).toBeLessThan(25)
    }
  })

  it('paints the native dashed comparison legend marker', async () => {
    const base = sectionOf(cahierExportFixture({}).content, 'aedar-access').evidence as any
    const served = {
      ...base,
      ramps: base.ramps.map((ramp: any) => ({
        ...ramp,
        reference: Object.fromEntries(Object.keys(ramp.territory).map((mode) => [mode,
          (ramp.territory[mode] as number[]).map((value) => value * 0.8)])),
      })),
    }
    const { page } = await generate(capturePdfFixture('aedar-access', { evidencePatch: served } as any))
    const ops = await page.getOperatorList()
    const dashed = ops.fnArray.some((op, index) => op === OPS.setDash
      && Array.from(ops.argsArray[index][0] as ArrayLike<number>).length > 0)
    expect(dashed).toBe(true)
  })

  it('omits explanatory prose on generated bytes but keeps figures, tables and sources', async () => {
    const prose = [
      'La diversité décrit le nombre de différents types',
      'Le nombre d’établissements ci-dessous décrit le volume',
      'Les places vélo proviennent du hub Ecolab',
      'Les bornes de recharge (IRVE) et les stations-service',
      'La courbe lit la part de la population bretonne joignable',
      'À 1 h 30 (90 min), 13 %',
      'Les parts portent sur toute la population bretonne',
    ]
    for (const key of ['aedar-access', 'aedar-car-overview', 'stationnement-ravitaillement', 'visiter-la-bretagne'] as const) {
      const { items, pdf } = await generate(capturePdfFixture(key))
      const text = items.map((item) => item.str).join(' ').replace(/\s+/g, ' ')
      for (const sentence of prose) expect(text, `${key}: ${sentence}`).not.toContain(sentence)
      expect(/Valeurs du graphique|Valeurs des graphiques/.test(text), key).toBe(true)
      expect(pdf.numPages).toBeGreaterThanOrEqual(1)
    }
    const station = await generate(capturePdfFixture('stationnement-ravitaillement'))
    expect(station.items.map((item) => item.str).join(' ')).toContain('Stationnement vélo et voiture')
    expect(station.items.map((item) => item.str).join(' ')).toContain('Source(s)')
  })
}, 120000)
