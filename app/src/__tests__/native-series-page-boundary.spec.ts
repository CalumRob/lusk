import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { chargerCatalogueRessources, lireRessourcesBatch } from '@/payload/semanticResourceClient'
import type { SemanticReadItem } from '@/payload/semanticResourceClient'
import { orderedSeriesFacts } from '@/payload/orderedSeriesAdapter'
import type { OrderedSeriesRead } from '@/payload/orderedSeriesAdapter'
import { dispatchIndicatorFamily } from '@/indicateurs/familySeam'
import { modeleTrajectoire } from '@/indicateurs/explorationModel'
import { validerThemeMetadata } from '@/payload/validate'
import type { Territoire } from '@/payload/types'

// Generated by the guarded SQL/public-HTTP capture, not a TS success fixture.
const wire = JSON.parse(readFileSync(process.env.LUSK_NATIVE_SERIES_CAPTURE ??
  join(__dirname, 'fixtures/native-state-calendar-boundary.json'), 'utf8'))
const metadata = validerThemeMetadata(JSON.parse(readFileSync(
  join(process.cwd(), '../pipeline/inst/extdata/theme-metadata/theme_milieux.json'), 'utf8')), 'theme_milieux.json')

afterEach(() => vi.unstubAllGlobals())

async function readNative(name: 'cohort' | 'focal' | 'fixed' | 'calendar' | 'selected') {
  const captured = wire[name]
  const fetcher = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
    if (String(input) === '/api/resources') return Response.json(wire.catalogue)
    expect(String(input)).toBe('/api/resources/read-batch')
    expect(JSON.parse(String(init?.body))).toEqual(captured.request)
    return Response.json(captured.response, { status: captured.response_status })
  })
  vi.stubGlobal('fetch', fetcher)
  const catalogue = await chargerCatalogueRessources()
  const { id: _id, ...item } = captured.request.items[0]
  const [data] = await lireRessourcesBatch([item as SemanticReadItem])
  expect(data).toEqual(captured.response.results[0].data)
  expect(catalogue.find((row) => row.resource_id === 'artif_par_habitant')?.shapes).toContain('ordered_series')
  return data!
}

describe('#857 guarded native stock/calendar boundary → real application seams', () => {
  it('passes the unmodified public cohort and focal responses through actual app callables', async () => {
    const cohort = await readNative('cohort')
    expect((cohort.cohort as any).members.map((row: any) => row.type)).toEqual(['epci', 'epci', 'epci'])
    const focal = await readNative('focal')
    const facts = orderedSeriesFacts(focal as unknown as OrderedSeriesRead, 'milieux', wire.territories as Territoire[])
    const page = metadata.indicator_pages!.artif_par_habitant!
    const family = dispatchIndicatorFamily(page, {
      theme: 'milieux', facts, territories: wire.territories, selected: 'state-e1', facet: { detail: '2023' },
    })
    expect(family.family).toBe('trajectory')
    expect(family.selected).toMatchObject({ value: 120, unit: 'm²/hab', observation_period: '2020–2023' })
    const model = modeleTrajectoire(facts, family.facet, ['M2', 'M3'], wire.territories,
      { niveau: 'epci', territoire: 'state-e1' }, [], null, { nativeSeries: true })
    expect(model.serieTerritoire?.find((point) => point.detail === '2023')?.value).toBe(120)
    expect(model.etapes.find((step) => step.detail === '2023')).toMatchObject({ mediane: null,
      min: null, max: null, comparisonSupported: false })
    expect(model.etapes.map((step) => step.detail)).toEqual(expect.arrayContaining(
      ['M2', 'M3', '2020', '2021', '2022', '2023', '2024', '2025']))
  })

  it('shows why selecting typed EPCI is not an alternative same-level peer contract', async () => {
    const data = await readNative('selected')
    expect(data.selection).toEqual([
      { territory_type: 'epci', territory_id: 'state-e1' },
      { territory_type: 'epci', territory_id: 'state-e2' },
      { territory_type: 'epci', territory_id: 'state-e3' },
    ])
    expect(data.scope).toEqual({ kind: 'explicit_selection', member_count: 3 })
    // Actual resolved commune population has one 2025 value, unlike EPCI 2023.
    expect(data.result).toMatchObject({ source_facet: '2025', eligible_count: 1, missing_count: 2,
      status: 'unavailable', reason: 'selected_coordinate_has_no_comparison_result' })
  })

  it('keeps calendar facts but refuses calendar peer evidence under the approved restriction', async () => {
    const fixed = await readNative('fixed')
    expect(fixed.result).toMatchObject({ statistic: 'median', median: 180, eligible_count: 3 })
    const calendar = await readNative('calendar')
    // Owner decision: these remain calendar facts, not a comparison population.
    // Preserve the old unrequested response rather than relabel its M3 fallback.
    expect(calendar.result).toMatchObject({ source_facet: '2025', statistic: 'median', status: 'unavailable',
      reason: 'selected_coordinate_has_no_comparison_result' })
    expect(calendar.result).not.toHaveProperty('median')
  })
})
