BEGIN;

-- ADR-0049 step 2 (#1137): per-resource publication registry, append-only
-- receipts and per-resource scalar comparison markers. STRICTLY ADDITIVE:
-- no existing row, publication marker, global scalar snapshot, constraint or
-- grant is changed. `table_publication['scalar_observation']` and the
-- `scalar_comparison_publication` singleton are deliberately left in place —
-- the current API keeps reading them until step 4 (#1140). Applying this DDL
-- alone publishes no resource.
--
-- Like every migration in this directory, this file OWNS its transaction:
-- apply it with psql --set ON_ERROR_STOP=on and WITHOUT --single-transaction.

-- One row per Ressource semantique de service: the single answer to "what is
-- live". Shape is one of the five registered shapes; `retired` lets `apply
-- --retire` keep a receipt while taking a resource out of the live set.
CREATE TABLE IF NOT EXISTS resource_publication (
    resource_id text PRIMARY KEY CHECK (resource_id ~ '^[a-z][a-z0-9_]{0,95}$'),
    shape text NOT NULL CHECK (shape IN
      ('scalar','declared_profile','owned_series','observed_collection','aedar')),
    content_version text NOT NULL CHECK (length(content_version) > 0),
    reference_content_version text,
    published_at timestamptz NOT NULL DEFAULT now(),
    retired boolean NOT NULL DEFAULT false
);

-- Append-only publication receipt. One row per applied resource: old -> new
-- version, operation, commit SHA, time, confirmed-definition flag and the
-- lineage digests that were attested. UPDATE/DELETE/TRUNCATE are forbidden by
-- a trigger as well as by the grant model below, so the history survives even
-- if a future role is granted broad DML on the schema.
CREATE TABLE IF NOT EXISTS resource_publication_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id text NOT NULL CHECK (resource_id ~ '^[a-z][a-z0-9_]{0,95}$'),
    shape text NOT NULL CHECK (shape IN
      ('scalar','declared_profile','owned_series','observed_collection','aedar')),
    operation text NOT NULL CHECK (operation IN ('apply','retire','adopt')),
    old_content_version text,
    new_content_version text,
    commit_sha text,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    confirmed_definition boolean NOT NULL DEFAULT false,
    lineage_digests jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE OR REPLACE FUNCTION resource_publication_event_append_only()
RETURNS trigger LANGUAGE plpgsql AS $m046_append$
BEGIN
  RAISE EXCEPTION 'resource_publication_event is append-only (ADR-0049)';
END $m046_append$;

DO $m046_trigger$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger t JOIN pg_class r ON r.oid=t.tgrelid
    JOIN pg_namespace n ON n.oid=r.relnamespace
    WHERE n.nspname=current_schema() AND r.relname='resource_publication_event'
      AND t.tgname='resource_publication_event_no_write'
  ) THEN
    CREATE TRIGGER resource_publication_event_no_write
      BEFORE UPDATE OR DELETE ON resource_publication_event
      FOR EACH ROW EXECUTE FUNCTION resource_publication_event_append_only();
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger t JOIN pg_class r ON r.oid=t.tgrelid
    JOIN pg_namespace n ON n.oid=r.relnamespace
    WHERE n.nspname=current_schema() AND r.relname='resource_publication_event'
      AND t.tgname='resource_publication_event_no_truncate'
  ) THEN
    CREATE TRIGGER resource_publication_event_no_truncate
      BEFORE TRUNCATE ON resource_publication_event
      FOR EACH STATEMENT EXECUTE FUNCTION resource_publication_event_append_only();
  END IF;
END $m046_trigger$;

-- Per-resource scalar comparison marker. It coexists with the global
-- `scalar_comparison_publication` singleton (expand phase): `apply` writes
-- this row for the one indicator it publishes and NEVER touches the singleton.
-- The group/territory/lineage rows remain keyed by indicator_id, so they are
-- already per-resource; this marker only replaces the global clock for reads
-- that will move to per-resource in step 4.
CREATE TABLE IF NOT EXISTS scalar_resource_comparison_publication (
    indicator_id text PRIMARY KEY REFERENCES scalar_descriptor(indicator_id),
    content_version text NOT NULL,
    scalar_content_version text NOT NULL,
    reference_content_version text NOT NULL,
    group_row_count integer NOT NULL CHECK (group_row_count >= 0),
    territory_row_count integer NOT NULL CHECK (territory_row_count >= 0),
    lineage_row_count integer NOT NULL CHECK (lineage_row_count >= 0),
    published_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON resource_publication, resource_publication_event,
  scalar_resource_comparison_publication TO lusk_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON resource_publication,
  scalar_resource_comparison_publication TO lusk_publisher;
-- Receipts: INSERT/SELECT only. No UPDATE, DELETE or TRUNCATE grant.
GRANT SELECT, INSERT ON resource_publication_event TO lusk_publisher;
REVOKE UPDATE, DELETE, TRUNCATE ON resource_publication_event FROM lusk_publisher;

COMMIT;
